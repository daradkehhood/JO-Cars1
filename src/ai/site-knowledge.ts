function getBrandPriceContext(): string {
  const lines = Object.entries(BRAND_PRICE_RANGES).map(
    ([, data]) => `- ${data.nameAr}: ${data.min.toLocaleString()}-${data.max.toLocaleString()} د.أ — الأكثر مبيعاً: ${data.popular.join('، ')}`
  );
  return `نطاقات أسعار الماركات في الأردن (2026):\n${lines.join('\n')}`;
}

/**
 * Get the full system prompt for a specific AI feature.
 */
export function getSystemPrompt(feature: 'price-estimate' | 'condition' | 'analysis' | 'chat' | 'engine-sound' | 'description'): string {
  const base = `${SITE_OVERVIEW}\n\n${JORDANIAN_MARKET_CONTEXT}\n\n${SITE_FEATURES}\n\n${FAQ}`;

  switch (feature) {
    case 'price-estimate':
      return `${base}\n\nأنت خبير تقييم أسعار السيارات في الأردن.\n- أعطِ سعراً عادلاً بالدينار الأردني\n- اذكر العوامل الرئيسية المؤثرة\n- قدم نطاق سعر منطقي (أدنى وأعلى)\n- استخدم بيانات السوق إن توفرت\n- لا تبالغ — كن واقعياً\n\n${getBrandPriceContext()}`;

    case 'condition':
      return `${base}\n\nأنت خبير فحص وتقييم حالة السيارات.\n- قدم درجة من 0 إلى 100\n- قيم الحالة (خارج، داخلي، محرك)\n- اذكر الإيجابيات والسلبيات`;

    case 'analysis':
      return `${base}\n\nأنت محلل أسعار سيارات محترف.\n- قيم السعر مقارنة بالسوق\n- أعطِ تقييم: منخفض 🟢 / عادل 🟡 / مرتفع 🔴\n- قدم توصية عملية\n\n${getBrandPriceContext()}`;

    case 'chat':
      return getEnhancedChatPrompt();

    case 'engine-sound':
      return `${base}\n\nأنت خبير تحليل أصوات محركات السيارات.\n- قيم صحة المحرك بناءً على المواصفات\n- اذكر المشاكل المحتملة\n- قدم توصيات صيانة وقائية`;

    case 'description':
      return `${base}\n\nأنت كاتب إعلانات سيارات محترف.\n- اكتب وصفاً جذاباً وواقعياً بالعربية\n- اذكر الميزات الرئيسية\n- لا تبالغ`;

    default:
      return base;
  }
}

