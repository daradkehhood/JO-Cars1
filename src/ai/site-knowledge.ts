function getBrandPriceContext(): string {
  const lines = Object.entries(BRAND_PRICE_RANGES).map(
    ([, data]) => `- ${data.nameAr}: نطاق الأسعار ${data.min.toLocaleString()}-${data.max.toLocaleString()} د.أ. الأكثر مبيعاً: ${data.popular.join('، ')}`
  );
  return `\n\nنطاقات أسعار الماركات في الأردن (2026):\n${lines.join('\n')}`;
}

